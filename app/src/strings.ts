const tables: Record<string, Partial<Record<StringKey, string>>> = { 'zh-Hans': zhHans, 'zh-Hant': zhHans }
let table: Partial<Record<StringKey, string>> = {}

export function setLanguage(lang: string): void {
  table = tables[lang] ?? {}
  document.documentElement.lang = lang
}

export function s(key: StringKey, vars: Record<string, string | number> = {}): string {
  const raw = table[key] ?? en[key]
  return raw.replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(vars[k] ?? ''))
}
